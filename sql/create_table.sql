CREATE TABLE crime_incidents (
    id BIGINT,
    case_number VARCHAR(50),
    date TIMESTAMP,
    block VARCHAR(255),
    iucr VARCHAR(20),
    primary_type VARCHAR(100),
    description VARCHAR(255),
    location_description VARCHAR(255),
    arrest BOOLEAN,
    domestic BOOLEAN,
    beat INT,
    district INT,
    ward INT,
    community_area INT,
    fbi_code VARCHAR(20),
    x_coordinate FLOAT,
    y_coordinate FLOAT,
    latitude FLOAT,
    longitude FLOAT,
    location TEXT,
    year INT,
    updated_on TIMESTAMP
);